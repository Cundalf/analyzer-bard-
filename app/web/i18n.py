def translations(lang: str = "es") -> dict[str, str]:
    return STRINGS.get(lang[:2].lower(), STRINGS["es"])


def detect_lang(request: Any) -> str:
    try:
        accept = request.headers.get("accept-language", "") or ""
        explicit = request.query_params.get("lang")
        if explicit:
            return explicit[:2]
        if accept.lower().startswith("en"):
            return "en"
    except Exception:
        pass
    return "es"
